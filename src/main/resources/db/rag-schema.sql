-- Tables for answering PDF questions with retrieval (RAG).
-- Production runs Hibernate with ddl-auto=validate, which checks the schema but never creates
-- tables, so the Heroku profile runs this script first. Every statement is safe to repeat on
-- each startup.

CREATE TABLE IF NOT EXISTS indexed_documents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    s3key           VARCHAR(1000) NOT NULL UNIQUE,
    pages_indexed   INTEGER       NOT NULL,
    total_pages     INTEGER       NOT NULL,
    chunk_count     INTEGER       NOT NULL,
    embedding_model VARCHAR(100)  NOT NULL,
    indexed_at      TIMESTAMP(6)  NOT NULL
);

CREATE TABLE IF NOT EXISTS document_chunks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT  NOT NULL REFERENCES indexed_documents (id),
    page_number INTEGER NOT NULL,
    chunk_index INTEGER NOT NULL,
    content     TEXT    NOT NULL,
    embedding   BYTEA   NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_document_chunks_document_id ON document_chunks (document_id);
